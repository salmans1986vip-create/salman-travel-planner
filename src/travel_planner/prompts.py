"""
قوالب التعليمات (Prompt Engineering).

مبادئ التصميم:
1. دور واضح للنموذج (مخطط رحلات سعودي محترف).
2. سياق مُسترجع من قاعدة البيانات فقط (Grounding): جدول أنشطة مرقّم.
3. قيود صريحة: عدد الأيام، الحد اليومي، عدم التكرار، الالتزام بالأرقام.
4. منع الاختلاق: ممنوع ذكر أي نشاط أو سعر غير موجود في الجدول.
5. لا حساب أرقام: التكلفة تُحسب برمجياً، والنموذج يركّز على الاختيار والترتيب.
6. مخرجات منظمة: تعليمات تنسيق JSON يولّدها PydanticOutputParser تلقائياً.
7. تغذية راجعة: متغير {feedback} يحمل أخطاء المحاولة السابقة عند إعادة المحاولة.
"""
from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder

SYSTEM_PROMPT = """أنت "رفيق"، مساعد ذكي محترف في تخطيط الرحلات داخل المملكة العربية السعودية.
مهمتك بناء برنامج سفر يومي واقعي ومتوازن بناءً على بيانات الأنشطة المرفقة فقط.

القواعد الإلزامية:
1. استخدم فقط الأنشطة الموجودة في "جدول الأنشطة المتاحة"، واكتب رقمها (activity_id) واسمها كما هما تماماً.
2. لا تخترع أنشطة أو أماكن أو أسعاراً أو مواعيد غير موجودة في الجدول.
3. عدد الأيام في الخطة يساوي عدد أيام الرحلة المطلوب بالضبط، مرقمة من 1.
4. من 2 إلى {max_per_day} أنشطة لكل يوم، ولا تكرر النشاط نفسه في الرحلة.
5. رتّب أنشطة اليوم حسب الفترة (صباحاً ثم ظهراً ثم عصراً ثم مساءً) واستفد من "الوقت المفضل" لكل نشاط.
6. قدّم الأنشطة المطابقة لاهتمامات المسافر، وأضف وجبة أو مطعماً في معظم الأيام إن توفر.
7. راعِ الميزانية: إذا كانت محدودة ففضّل الأنشطة المجانية والأقل تكلفة. لا تحسب المجاميع؛ النظام يحسبها.
8. إذا كانت الأنشطة المتاحة أقل من المطلوب، قلّل عدد الأنشطة اليومية بدلاً من التكرار أو الاختلاق.
9. اكتب بالعربية الفصحى المبسطة، وبإيجاز.
10. أعد المخرجات بصيغة JSON فقط وفق التنسيق المطلوب، دون أي نص قبله أو بعده."""

PLANNING_HUMAN = """## بيانات الرحلة
- الوجهة: {destination} — {destination_description}
- عدد الأيام: {days}
- عدد المسافرين: {travelers}
- الميزانية الإجمالية: {budget} ريال
- التكلفة الأساسية التقديرية (سكن + أكل + تنقل): {base_cost} ريال
- المتبقي تقريباً للأنشطة: {activities_budget} ريال
- الاهتمامات: {interests}
- ملاحظات المسافر: {notes}

## جدول الأنشطة المتاحة (المصدر الوحيد المسموح به)
{activities_table}

{feedback}

## تنسيق المخرجات
{format_instructions}"""

REVISION_HUMAN = """## سياق الرحلة الحالية
{trip_context}

## الخطة الحالية (JSON)
{current_plan}

## جدول الأنشطة المتاحة (المصدر الوحيد المسموح به)
{activities_table}

## طلب التعديل من المسافر
{request}

عدّل الخطة لتلبية الطلب مع الالتزام بجميع القواعد، وأبقِ ما لم يطلب المسافر تغييره كما هو.
إذا كان الطلب غير ممكن بالبيانات المتاحة فاذكر ذلك في الملخص وأعد أقرب خطة ممكنة.

{feedback}

## تنسيق المخرجات
{format_instructions}"""


def planning_prompt() -> ChatPromptTemplate:
    """قالب إنشاء خطة جديدة."""
    return ChatPromptTemplate.from_messages(
        [("system", SYSTEM_PROMPT), ("human", PLANNING_HUMAN)]
    )


def revision_prompt() -> ChatPromptTemplate:
    """قالب تعديل خطة قائمة؛ يتضمن سجل المحادثة السابق (الذاكرة)."""
    return ChatPromptTemplate.from_messages(
        [
            ("system", SYSTEM_PROMPT),
            MessagesPlaceholder(variable_name="history"),
            ("human", REVISION_HUMAN),
        ]
    )
